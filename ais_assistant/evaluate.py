"""Run the 20-question test set and write the results table.

    python -m ais_assistant.evaluate

Writes eval/results.json (every reply with its agent trace) and eval/results.md
(the table in the README). Scoring is automatic and deliberately simple, so
anyone can re-run it and get the same numbers:

  * correct      - "answer" cases: answered AND every must_include group matched.
                   "dont_know": said it does not know. "decline": refused politely.
  * right source - "answer" cases: at least one linked page is an expected page.
                   "dont_know" cases: the contact page is linked.
  * made up      - a fact the site does not support: answered a question it should have
                   refused, or used a forbidden string (e.g. a client name the site never gives).

The automatic score can be wrong in both directions, so I also read every answer by hand;
disagreements are written up in eval/results.md under "Manual review".
"""

from __future__ import annotations

import json
import logging
import time
from collections import defaultdict

from . import config
from .orchestrator import Conversation, Orchestrator

TYPE_LABELS = {
    "answered_on_site": "Answered on the website",
    "follow_up": "Follow-up",
    "not_on_site": "Not on the website",
    "off_topic_or_tricky": "Off-topic or tricky",
}


def score(case: dict, reply) -> dict:
    text = reply.text.lower()
    urls = [url for _, url in reply.sources]
    forbidden = [s for s in case.get("must_not_include", []) if s in reply.text]  # case-sensitive on purpose

    if case["expect"] == "answer":
        correct = reply.status == "answered" and all(
            any(alt.lower() in text for alt in group) for group in case.get("must_include", []))
        right_source = any(u in case["expected_sources"] for u in urls)
        made_up = bool(forbidden)
    elif case["expect"] == "dont_know":
        correct = reply.status == "unknown" and not forbidden
        right_source = config.CONTACT_URL in urls
        made_up = reply.status == "answered" or bool(forbidden)
    else:  # decline
        correct = reply.status in ("off_topic", "small_talk", "unknown")
        right_source = None  # no source expected
        made_up = reply.status == "answered"
    return {"correct": correct, "right_source": right_source, "made_up": made_up}


def run() -> list[dict]:
    cases = json.loads(config.TEST_SET_FILE.read_text())
    orchestrator = Orchestrator()
    results = []
    for case in cases:
        conversation = Conversation(orchestrator)
        start = time.perf_counter()
        for turn in case["turns"][:-1]:  # setup turns for follow-ups
            conversation.ask(turn)
        reply = conversation.ask(case["turns"][-1])
        seconds = round(time.perf_counter() - start, 1)
        result = {**case, "status": reply.status, "actual_answer": reply.text, "query": reply.query,
                  "sources": [url for _, url in reply.sources], "trace": reply.trace,
                  "seconds": seconds, **score(case, reply)}
        print(f"{case['id']}  {'OK ' if result['correct'] else 'BAD'}  {reply.status:<10} {seconds:>5}s  "
              f"{reply.text[:90]}")
        results.append(result)
    return results


def _mark(value) -> str:
    return "-" if value is None else ("yes" if value else "**no**")


def write_report(results: list[dict]) -> str:
    by_type = defaultdict(list)
    for r in results:
        by_type[r["type"]].append(r)

    lines = ["# Evaluation results", "",
             f"Model `{config.OLLAMA_MODEL}`, embeddings `{config.EMBEDDING_MODEL}`, "
             f"top-k {config.TOP_K}, min relevance {config.MIN_RELEVANCE}. "
             "Generated by `python -m ais_assistant.evaluate`.", "",
             "## Summary", "",
             "| Question type | Questions | Correct | Right source | Made something up |",
             "|---|---|---|---|---|"]
    for t, label in TYPE_LABELS.items():
        rs = by_type.get(t, [])
        sourced = [r for r in rs if r["right_source"] is not None]
        src = f"{sum(r['right_source'] for r in sourced)}/{len(sourced)}" if sourced else "-"
        lines.append(f"| {label} | {len(rs)} | {sum(r['correct'] for r in rs)}/{len(rs)} | {src} | "
                     f"{sum(r['made_up'] for r in rs)} |")
    sourced = [r for r in results if r["right_source"] is not None]
    lines.append(f"| **Total** | {len(results)} | **{sum(r['correct'] for r in results)}/{len(results)}** | "
                 f"**{sum(r['right_source'] for r in sourced)}/{len(sourced)}** | "
                 f"**{sum(r['made_up'] for r in results)}** |")
    avg = sum(r["seconds"] for r in results) / max(len(results), 1)
    lines += ["", f"Average time per question: {avg:.1f} s (CPU/Apple-silicon laptop, includes follow-up setup turns).",
              "", "## Every question", "",
              "| ID | Question | Expected | Actual answer | Sources | Correct | Source | Made up |",
              "|---|---|---|---|---|---|---|---|"]
    for r in results:
        question = " → ".join(r["turns"])
        sources = "<br>".join(r["sources"]) or "-"
        cells = [r["id"], question, r["expected_answer"], r["actual_answer"], sources,
                 _mark(r["correct"]), _mark(r["right_source"]), "**yes**" if r["made_up"] else "no"]
        lines.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    logging.basicConfig(level=logging.WARNING)
    results = run()
    config.EVAL_DIR.mkdir(exist_ok=True)
    (config.EVAL_DIR / "results.json").write_text(json.dumps(results, indent=2, ensure_ascii=False))
    report = write_report(results)
    report_file = config.EVAL_DIR / "results.md"
    # keep the hand-written manual review section when re-running
    old = report_file.read_text() if report_file.exists() else ""
    if "\n## Manual review" in old:
        report += "\n## Manual review" + old.split("\n## Manual review", 1)[1]
    report_file.write_text(report)
    print(f"\nWrote {report_file}")


if __name__ == "__main__":
    main()
